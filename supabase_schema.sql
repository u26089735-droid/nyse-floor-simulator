create table if not exists public.profiles (
  user_id text primary key,
  username text not null check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  display_name text not null default 'Trader',
  avatar_url text,
  equity numeric(16,2) not null default 25000,
  peak_equity numeric(16,2) not null default 25000,
  career_day integer not null default 1,
  current_rank text not null default 'Junior Floor Trader',
  experience_mode text not null default 'beginner' check (experience_mode in ('beginner', 'pro')),
  settings jsonb not null default '{}'::jsonb,
  badges jsonb not null default '[]'::jsonb,
  last_close jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_username_ci_key
  on public.profiles (lower(username));
create index if not exists profiles_equity_order_idx
  on public.profiles (equity desc, username asc);

create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  user_id text not null references public.profiles(user_id) on delete cascade,
  client_trade_id uuid not null,
  symbol text not null,
  side text not null check (side in ('LONG', 'SHORT')),
  qty numeric(20,6) not null,
  entry_price numeric(20,6) not null,
  exit_price numeric(20,6) not null,
  net_pnl numeric(20,2) not null,
  mae numeric(12,4) not null default 0,
  mfe numeric(12,4) not null default 0,
  journal_notes text not null default '',
  tags text[] not null default '{}',
  trade_day integer not null default 1,
  exit_time text not null default '',
  created_at timestamptz not null default now(),
  unique (user_id, client_trade_id)
);

alter table public.profiles enable row level security;
alter table public.trades enable row level security;

revoke all on public.profiles, public.trades from public, anon, authenticated;
grant all on public.profiles, public.trades to service_role;
grant usage, select on sequence public.trades_id_seq to service_role;
grant select (username, display_name, avatar_url, equity, current_rank)
  on public.profiles to anon, authenticated;

drop policy if exists "Public leaderboard profiles are readable" on public.profiles;
create policy "Public leaderboard profiles are readable"
  on public.profiles for select to anon, authenticated using (true);

create or replace view public.leaderboard_public
  with (security_invoker = true) as
  select username, display_name, avatar_url, equity, current_rank
  from public.profiles;

revoke all on public.leaderboard_public from public, anon, authenticated;
grant select on public.leaderboard_public to anon, authenticated;
